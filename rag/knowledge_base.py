INDEX_DIR = os.path.join(os.path.dirname(__file__), "index")


def build_index(model_name: str = "jhgan/ko-sroberta-multitask"):
    """
    지식베이스를 임베딩하고 FAISS 인덱스를 생성합니다.

    왜 jhgan/ko-sroberta-multitask 인가:
    - 한국어 특화 sentence-transformer 모델
    - 문장 유사도 태스크에 fine-tuned됨
    - 768차원 벡터, 로컬 실행 가능, 무료
    """
    print(f"[RAG] 임베딩 모델 로딩: {model_name}")
    model = SentenceTransformer(model_name)

    texts = []
    for chunk in KNOWLEDGE_CHUNKS:
        # 검색 품질 향상을 위해 질문 + 답변을 합쳐서 임베딩
        # → 질문만 임베딩하면 답변 내용으로 검색할 때 못 찾는 경우 발생
        combined = f"{chunk['question']} {chunk['answer']}"
        texts.append(combined)

    print(f"[RAG] {len(texts)}개 청크 임베딩 중...")
    embeddings = model.encode(texts, show_progress_bar=True, convert_to_numpy=True)

    # L2 정규화 → cosine similarity 검색 가능하게
    faiss.normalize_L2(embeddings)

    # IndexFlatIP: 내적(inner product) 기반 검색 = 정규화 후 cosine similarity
    # 왜 Flat인가: 청크가 수십~수백 개 수준 → approximate 인덱스(IVF, HNSW) 불필요
    dimension = embeddings.shape[1]
    index = faiss.IndexFlatIP(dimension)
    index.add(embeddings)

    os.makedirs(INDEX_DIR, exist_ok=True)
    faiss.write_index(index, os.path.join(INDEX_DIR, "faiss.index"))

    with open(os.path.join(INDEX_DIR, "chunks.pkl"), "wb") as f:
        pickle.dump(KNOWLEDGE_CHUNKS, f)

    with open(os.path.join(INDEX_DIR, "meta.json"), "w", encoding="utf-8") as f:
        json.dump({"model_name": model_name, "num_chunks": len(KNOWLEDGE_CHUNKS)}, f, ensure_ascii=False, indent=2)

    print(f"[RAG] ✅ 인덱스 저장 완료: {INDEX_DIR}")
    print(f"[RAG] 총 {len(KNOWLEDGE_CHUNKS)}개 청크 인덱싱됨")


if __name__ == "__main__":
    build_index()
